/**
 * Writes supabase/migrations/20261125000004_seed.sql from data/*.seed.json.
 *
 *   npx tsx scripts/build-seed-sql.ts           # (re)write the file
 *   npx tsx scripts/build-seed-sql.ts --check   # exit 1 if the file is out of date with the JSON
 *
 * Same rows as scripts/seed-supabase.ts (same loader, mappers and validator), as plain SQL so the seed can be
 * applied as a migration without a service-role key. Idempotent: ON CONFLICT (id) DO NOTHING, so applying it twice
 * changes nothing and it never overwrites or deletes a row. To push later edits of the JSON into an existing
 * database, use `npm run seed:supabase` (upsert by id).
 *
 * The confidence cache column of country_facts is left empty on purpose: confidence is computed on read
 * (public.country_facts_computed), never stored as truth.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { buildSeedRows, validateSeedRows, type SeedRows } from '../src/lib/supabase/mappers';
import { loadSeedFiles } from './seed-files';

const root = process.cwd();
export const SEED_SQL_FILE = join(root, 'supabase', 'migrations', '20261125000004_seed.sql');

type ColumnType = 'text' | 'jsonb' | 'timestamptz' | 'date';

/** Column types that need a cast (everything else is text). */
const COLUMN_TYPES: Record<keyof SeedRows, Record<string, ColumnType>> = {
  institutions: { hec_status: 'jsonb', pqr_status: 'jsonb', anabin_status: 'jsonb', recognition_list_status: 'jsonb' },
  programs: { last_checked: 'date' },
  country_facts: { value: 'jsonb', conflicts: 'jsonb', fetched_at: 'timestamptz' },
  conversion_rules: { params: 'jsonb', fetched_at: 'timestamptz' },
  fx_rates: { pkr_per_unit: 'jsonb' },
};

/** Every object-valued column of programs is a jsonb fact. */
function columnType(table: keyof SeedRows, column: string, value: unknown): ColumnType {
  const declared = COLUMN_TYPES[table][column];
  if (declared) return declared;
  if (table === 'programs' && value !== null && typeof value === 'object') return 'jsonb';
  return 'text';
}

function quote(s: string): string {
  if (s.includes('\u0000')) throw new Error('NUL character in seed text');
  return `'${s.replace(/'/g, "''")}'`;
}

function literal(value: unknown, type: ColumnType): string {
  if (value === null || value === undefined) return 'null';
  if (type === 'jsonb') return `${quote(JSON.stringify(value))}::jsonb`;
  if (type === 'text') {
    if (typeof value !== 'string') throw new Error(`expected text, got ${typeof value}`);
    return quote(value);
  }
  return `${quote(String(value))}::${type}`;
}

/** Insert order respects foreign keys (programs reference institutions). */
const TABLE_ORDER: (keyof SeedRows)[] = ['institutions', 'programs', 'country_facts', 'conversion_rules', 'fx_rates'];

function insertStatement(table: keyof SeedRows, rows: Record<string, unknown>[]): string {
  if (rows.length === 0) return `-- ${table}: no rows\n`;
  const columns = Object.keys(rows[0]);
  for (const r of rows) {
    const keys = Object.keys(r);
    if (keys.length !== columns.length || keys.some((k, i) => k !== columns[i])) {
      throw new Error(`${table}: rows have different columns`);
    }
  }
  const values = rows.map((r) => `  (${columns.map((c) => literal(r[c], columnType(table, c, r[c]))).join(', ')})`);
  return [
    `insert into public.${table} (${columns.join(', ')}) values`,
    values.join(',\n'),
    'on conflict (id) do nothing;',
    '',
  ].join('\n');
}

/**
 * SQL that inserts ONLY the given programs (and institutions) from data/*.seed.json, for a later data migration.
 * Same literals, same validation, ON CONFLICT (id) DO NOTHING.
 */
export function buildAddedRowsSql(programIds: string[], institutionIds: string[], title: string): string {
  const rows = buildSeedRows(loadSeedFiles(root));
  const problems = validateSeedRows(rows);
  if (problems.length > 0) {
    throw new Error(`data/*.seed.json has ${problems.length} problem(s):\n  - ${problems.join('\n  - ')}`);
  }
  const programs = rows.programs.filter((p) => programIds.includes(p.id));
  const institutions = rows.institutions.filter((i) => institutionIds.includes(i.id));
  const missing = [
    ...programIds.filter((id) => !programs.some((p) => p.id === id)),
    ...institutionIds.filter((id) => !institutions.some((i) => i.id === id)),
  ];
  if (missing.length > 0) throw new Error(`not in data/programs.seed.json: ${missing.join(', ')}`);
  const header = [
    `-- ${title}`,
    '-- GENERATED by scripts/build-seed-sql.ts from data/programs.seed.json; do not edit by hand.',
    '-- Every value comes from an official page with a verbatim evidence_snippet (checked by scripts/add-programs.ts),',
    '-- or is null ("Not verified yet"). Idempotent: ON CONFLICT (id) DO NOTHING; it never overwrites or deletes a row.',
    `-- Rows: institutions ${institutions.length}, programs ${programs.length}.`,
    '',
  ].join('\n');
  const body = [
    institutions.length ? insertStatement('institutions', institutions as unknown as Record<string, unknown>[]) : '',
    insertStatement('programs', programs as unknown as Record<string, unknown>[]),
  ].filter(Boolean).join('\n');
  return `${header}\n${body}`;
}

export function buildSeedSql(): string {
  // No `now`: the confidence cache column stays null (computed on read instead).
  const rows = buildSeedRows(loadSeedFiles(root));
  const problems = validateSeedRows(rows);
  if (problems.length > 0) {
    throw new Error(`data/*.seed.json has ${problems.length} problem(s):\n  - ${problems.join('\n  - ')}`);
  }
  const counts = TABLE_ORDER.map((t) => `${t} ${rows[t].length}`).join(', ');
  const header = [
    '-- MastersPath 004 (25 Nov 2026): seed data. GENERATED by scripts/build-seed-sql.ts from data/*.seed.json;',
    '-- do not edit by hand (run `npm run seed:sql`).',
    '--',
    '-- Every value below comes from the reviewed seed files, each with its own source_url, verbatim evidence_snippet',
    '-- and fetched_at, or null ("Not verified yet"). No requirement value was typed in here.',
    '-- Idempotent: ON CONFLICT (id) DO NOTHING. It never overwrites or deletes a row; to push later JSON edits into',
    '-- an existing database use `npm run seed:supabase` (upsert by id).',
    '-- country_facts.confidence (a cache) is left null: confidence is computed on read (country_facts_computed).',
    `-- Rows: ${counts}.`,
    '',
  ].join('\n');
  const body = TABLE_ORDER.map((t) => insertStatement(t, rows[t] as unknown as Record<string, unknown>[])).join('\n');
  return `${header}\n${body}`;
}

function flag(name: string): string | null {
  const hit = process.argv.find((a) => a.startsWith(`--${name}=`));
  return hit ? hit.slice(name.length + 3) : null;
}

function main() {
  // Added rows only:  --programs=id1,id2 [--institutions=id3] --out=supabase/migrations/<version>_<name>.sql --title="..."
  const programs = flag('programs');
  if (programs) {
    const out = flag('out');
    if (!out) throw new Error('--out=<file> is required with --programs');
    const list = (v: string | null) => (v ? v.split(',').map((s) => s.trim()).filter(Boolean) : []);
    const sql = buildAddedRowsSql(list(programs), list(flag('institutions')), flag('title') ?? 'MastersPath: added programs');
    writeFileSync(join(root, out), sql, 'utf8');
    console.log(`build-seed-sql: wrote ${out} (${Buffer.byteLength(sql)} bytes).`);
    return;
  }
  const sql = buildSeedSql();
  if (process.argv.includes('--check')) {
    let current = '';
    try {
      current = readFileSync(SEED_SQL_FILE, 'utf8');
    } catch {
      /* missing file = out of date */
    }
    if (current.replace(/\r\n/g, '\n') !== sql) {
      console.error('build-seed-sql: supabase/migrations/20261125000004_seed.sql is out of date. Run `npm run seed:sql`.');
      process.exit(1);
    }
    console.log('build-seed-sql: seed migration is up to date.');
    return;
  }
  writeFileSync(SEED_SQL_FILE, sql, 'utf8');
  console.log(`build-seed-sql: wrote ${SEED_SQL_FILE} (${Buffer.byteLength(sql)} bytes).`);
}

main();
